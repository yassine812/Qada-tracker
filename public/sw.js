/* Generated build identity and complete offline manifest are injected after Vite. */
const BUILD_ID = '__QADA_BUILD_ID__';
const PRECACHE_URLS = /*__QADA_PRECACHE__*/ [];
const CACHE_NAME = `qada-static-${BUILD_ID}`;
const RUNTIME_CACHE = 'qada-runtime-v1';
const READY_URL = '/__qada_offline_ready__';
const requiredPaths = new Set(PRECACHE_URLS);

function unavailable() {
  return new Response('هذا المحتوى غير متاح دون اتصال حالياً.', {
    status: 503,
    headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
  });
}

async function requiredResponse(path) {
  const response = await fetch(new Request(path, { cache: 'reload', credentials: 'same-origin' }));
  if (!response.ok || response.type === 'opaque') throw new Error(`Required download failed: ${path}`);
  const contentType = (response.headers.get('Content-Type') || '').toLowerCase();
  if (path.endsWith('.html')) {
    const html = await response.clone().text();
    const marker = html.match(/<meta\s+name=["']qada-build["']\s+content=["']([^"']+)["']/i);
    if (!contentType.includes('text/html') || marker?.[1] !== BUILD_ID) {
      throw new Error('App shell belongs to a different deployment');
    }
  } else if (contentType.includes('text/html')) {
    // Static hosts commonly return a successful SPA fallback for a missing file.
    throw new Error(`HTML fallback cannot replace a required asset: ${path}`);
  }
  return response;
}

async function prepareCache(repair = false) {
  if (!PRECACHE_URLS.includes('/index.html') || BUILD_ID.startsWith('__')) {
    throw new Error('Offline manifest was not generated by the production build');
  }
  const cache = await caches.open(CACHE_NAME);
  await cache.delete(READY_URL);
  let cursor = 0;
  async function download() {
    // Every worker finishes its pending writes, including after another fails.
    const errors = [];
    while (cursor < PRECACHE_URLS.length) {
      const path = PRECACHE_URLS[cursor++];
      try {
        if (repair && await cache.match(path)) continue;
        await cache.put(path, await requiredResponse(path));
      } catch (error) {
        errors.push(error);
      }
    }
    if (errors.length) throw errors[0];
  }
  try {
    const outcomes = await Promise.allSettled(Array.from({ length: Math.min(6, PRECACHE_URLS.length) }, download));
    const failed = outcomes.find((result) => result.status === 'rejected');
    if (failed) throw failed.reason;
    await cache.put(READY_URL, new Response(JSON.stringify({ ready: true, buildId: BUILD_ID }), {
      headers: { 'Content-Type': 'application/json' },
    }));
  } catch (error) {
    // Failed new installations cannot replace the previous complete version.
    // Repair keeps surviving files usable, but never leaves a ready marker.
    if (!repair) await caches.delete(CACHE_NAME);
    else await cache.delete(READY_URL);
    throw error;
  }
}

async function offlineStatus() {
  try {
    const cache = await caches.open(CACHE_NAME);
    const response = await cache.match(READY_URL);
    if (!response) return { ready: false, buildId: BUILD_ID };
    const marker = await response.json();
    const keys = new Set((await cache.keys()).map((request) => new URL(request.url).pathname));
    const ready = marker.ready === true && marker.buildId === BUILD_ID &&
      PRECACHE_URLS.length > 0 && PRECACHE_URLS.every((path) => keys.has(path));
    return { ready, buildId: BUILD_ID };
  } catch {
    return { ready: false, buildId: BUILD_ID };
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(prepareCache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // Automatic activation can take over an older, still-open document. Keep
    // two prior builds for their immutable assets, without unbounded storage.
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    const names = await caches.keys();
    const previous = names.filter((name) => name !== CACHE_NAME && name.startsWith('qada-static-'));
    const retained = new Set(windows.length ? previous.slice(-2) : []);
    await Promise.all(names.filter((name) => name !== CACHE_NAME && !retained.has(name) && (
      name.startsWith('qada-static-') || (windows.length === 0 && (/^qada-v\d+$/.test(name) || /^qada-fonts-v\d+$/.test(name)))
    )).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

let repairing;
self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING' || event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting();
    return;
  }
  if (event.data?.type !== 'QADA_OFFLINE_STATUS' && event.data?.type !== 'QADA_REPAIR_OFFLINE') return;
  event.waitUntil((async () => {
    if (event.data.type === 'QADA_REPAIR_OFFLINE') {
      if (!repairing) repairing = prepareCache(true).catch(() => {}).finally(() => { repairing = undefined; });
      await repairing;
    }
    event.ports?.[0]?.postMessage(await offlineStatus());
  })());
});

async function appResponse(request, path) {
  try {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(path);
    if (cached) return cached;
    // Only content-hashed bundles may fall back to an earlier build. Never
    // reuse old HTML (including host-injected badges) or unversioned data.
    if (/^\/assets\/[^?]+-[\w-]{8,}\.(?:js|css|woff2?)$/i.test(path)) {
      for (const name of await caches.keys()) {
        if (name !== CACHE_NAME && name.startsWith('qada-static-')) {
          const previous = await (await caches.open(name)).match(path);
          if (previous && !(previous.headers.get('Content-Type') || '').toLowerCase().includes('text/html')) return previous;
        }
      }
    }
  } catch { /* Storage can be unavailable or evicted by the browser. */ }
  try {
    // Never overwrite a versioned asset or shell with another deployment.
    if (requiredPaths.has(path)) return await requiredResponse(path);
    return await fetch(request);
  } catch {
    return unavailable();
  }
}

async function optionalQuranResponse(request) {
  let cache;
  try {
    cache = await caches.open(RUNTIME_CACHE);
    const cached = await cache.match(request);
    if (cached) return cached;
  } catch { /* A browser denying cache storage must not block online reading. */ }
  try {
    const response = await fetch(request);
    if (cache && response.ok && response.type !== 'opaque' &&
        (response.headers.get('Content-Type') || '').includes('application/json')) {
      try { await cache.put(request, response.clone()); } catch { /* Optional cache quota failure is not fatal. */ }
    }
    return response;
  } catch {
    return unavailable();
  }
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.protocol !== 'https:' && url.protocol !== 'http:') return;
  if (request.destination === 'video' || request.destination === 'audio' || request.headers.has('Range') || /\.(mp4|mp3|m4a)$/i.test(url.pathname)) return;

  if (url.origin !== self.location.origin) {
    // Advertising/consent scripts and all other third-party requests pass through
    // untouched: they are never precached, intercepted, or replayed offline.
    if (url.protocol === 'https:' && url.hostname === 'api.alquran.cloud' && url.pathname.startsWith('/v1/')) {
      event.respondWith(optionalQuranResponse(request));
    }
    return;
  }

  if (request.mode === 'navigate') {
    const pagePath = url.pathname.endsWith('.html')
      ? url.pathname : `${url.pathname.replace(/\/$/, '')}/index.html`;
    event.respondWith(appResponse(request, requiredPaths.has(pagePath) ? pagePath : '/index.html'));
  } else {
    event.respondWith(appResponse(request, url.pathname + url.search));
  }
});

self.addEventListener('push', (event) => {
  let payload = {
    title: 'قضاء 🤲', body: 'تذكير يومي', icon: '/icons/icon-192.png',
    badge: '/icons/icon-192.png', tag: 'qada-push', data: { url: '/app' },
  };
  if (event.data) {
    try { payload = { ...payload, ...event.data.json() }; }
    catch { payload.body = event.data.text() || payload.body; }
  }
  event.waitUntil(self.registration.showNotification(payload.title, {
    body: payload.body, icon: payload.icon || '/icons/icon-192.png',
    badge: payload.badge || '/icons/icon-192.png', tag: payload.tag || 'qada-push',
    dir: 'rtl', lang: 'ar', vibrate: [200, 100, 200], data: payload.data || { url: '/app' },
  }));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  let targetUrl = new URL('/app', self.location.origin);
  try {
    const proposed = new URL(event.notification.data?.url || '/app', self.location.origin);
    if (proposed.origin === self.location.origin) targetUrl = proposed;
  } catch { /* Keep the safe application destination. */ }
  event.waitUntil((async () => {
    const clientList = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of clientList) {
      if (new URL(client.url).origin === self.location.origin) {
        await client.navigate(targetUrl.href);
        return client.focus();
      }
    }
    return self.clients.openWindow(targetUrl.href);
  })());
});
