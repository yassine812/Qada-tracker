import { build } from 'esbuild';
import { mkdir, readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { resolve, join, relative, isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { loadEnv } from 'vite';

const env = { ...loadEnv('production', process.cwd(), ''), ...process.env };
const client = env.VITE_ADSENSE_CLIENT || '';
if (client && !/^ca-pub-\d{16}$/.test(client)) throw new Error('Invalid public AdSense publisher ID');
if (env.VITE_ADS_ENABLED === 'true' && (
  !client || !/^\d{6,20}$/.test(env.VITE_ADSENSE_GUIDE_SLOT || '') || env.VITE_ADSENSE_APPROVED !== 'true' ||
  !env.VITE_PUBLISHER_NAME?.trim() || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(env.VITE_CONTACT_EMAIL || '')
)) throw new Error('Ads cannot be enabled before verified publisher, slot, approval and contact configuration');

const rawOrigin = env.SITE_URL || env.URL || '';
let origin = '';
if (rawOrigin) {
  const url = new URL(rawOrigin);
  if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash) throw new Error('SITE_URL must be a public HTTPS origin');
  origin = url.origin;
}
const escape = (value) => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const dist = resolve('dist');
let shell = await readFile(join(dist, 'index.html'), 'utf8');
if (client) shell = shell.replace('</head>', `<meta name="google-adsense-account" content="${client}">\n</head>`);
await writeFile(join(dist, 'index.html'), shell);
await writeFile(join(dist, 'ads.txt'), client
  ? `google.com, ${client.replace('ca-', '')}, DIRECT, f08c47fec0942fa0\n`
  : '# Advertising is not enabled. No authorized sellers configured.\n');

// Meaningful HTML for crawlers and users before JavaScript starts. No ad/CMP code
// executes during this build. Temporary bundling resolves local TSX on Windows.
await mkdir(resolve('artifacts'), { recursive: true });
const temporary = await mkdtemp(resolve('artifacts/public-build-'));
try {
  const output = join(temporary, 'info.mjs');
  await build({ entryPoints: [resolve('src/pages/InfoPage.tsx')], outfile: output, bundle: true,
    platform: 'node', format: 'esm', packages: 'external', jsx: 'automatic',
    define: { 'import.meta.env': JSON.stringify({ VITE_PUBLISHER_NAME: env.VITE_PUBLISHER_NAME || '', VITE_CONTACT_EMAIL: env.VITE_CONTACT_EMAIL || '' }) },
  });
  const { InfoPage } = await import(pathToFileURL(output).href);
  const routes = [
    ['/about', 'عن قضاء'], ['/privacy', 'الخصوصية والإعلانات'], ['/guides', 'دليل استخدام قضاء'],
    ['/guides/offline', 'استخدام قضاء دون اتصال'], ['/guides/backup', 'حفظ نسخة احتياطية من سجلاتك'],
  ];
  for (const [route, title] of routes) {
    const markup = renderToStaticMarkup(createElement(InfoPage, { path: route }));
    let html = shell.replace('<div id="root"></div>', `<div id="root">${markup}</div>`)
      .replace(/<title>.*?<\/title>/, `<title>${title} | قضاء</title>`);
    if (origin) html = html.replace('</head>', `<link rel="canonical" href="${escape(origin + route)}">\n</head>`);
    const directory = join(dist, route.slice(1));
    await mkdir(directory, { recursive: true });
    await writeFile(join(directory, 'index.html'), html);
  }
  const locations = ['/', ...routes.map(([route]) => route)];
  await writeFile(join(dist, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /app\n${origin ? `Sitemap: ${origin}/sitemap.xml\n` : ''}`);
  if (origin) await writeFile(join(dist, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${locations.map((route) => `<url><loc>${escape(origin + route)}</loc></url>`).join('')}</urlset>`);
  console.log(`Public HTML ready: ${routes.length} information pages. Ads ${env.VITE_ADS_ENABLED === 'true' ? 'configured, still consent-gated' : 'disabled'}.`);
} finally {
  // temporary is generated by mkdtemp under this workspace's artifacts directory.
  const temporaryRelative = relative(resolve('artifacts'), temporary);
  if (isAbsolute(temporaryRelative) || temporaryRelative.startsWith('..')) throw new Error('Unsafe temporary cleanup target');
  await rm(temporary, { recursive: true, force: true });
}
